import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import Link from "next/link";
import { auth, signOut } from "@/lib/auth";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const session = await auth();
  return (
    <html lang="en">
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        <header className="sticky top-0 z-30 border-b bg-white/70 dark:bg-black/40 backdrop-blur">
          <div className="max-w-6xl mx-auto px-4 h-14 flex items-center justify-between">
            <nav className="flex items-center gap-4 text-sm">
              <Link href="/" className="font-semibold">Infinite 8</Link>
              <Link href="/dashboard">Dashboard</Link>
            </nav>
            <div className="text-sm">
              {session?.user ? (
                <form action={async () => { "use server"; await signOut({ redirectTo: "/" }); }}>
                  <button className="px-3 py-1 rounded-md border">Sign out</button>
                </form>
              ) : (
                <Link className="px-3 py-1 rounded-md border" href="/sign-in">Sign in</Link>
              )}
            </div>
          </div>
        </header>
        {children}
      </body>
    </html>
  );
}
